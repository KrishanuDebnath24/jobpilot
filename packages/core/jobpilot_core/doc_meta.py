"""Document properties carried from the uploaded CV onto its tailored exports.

A tailored CV is rendered from scratch (reportlab / python-docx), so by default it arrives
stamped with the tools that made it — ``/Producer: ReportLab PDF Library``, a DOCX
``comments`` of "generated by python-docx", and, worst of all, python-docx's template
creation date of **2013-12-23**. Those are visible in any properties dialog, and none of
them describe the candidate's document.

This module reads the properties off the CV the candidate actually uploaded and replays
them onto every tailored render, so the exports match the original rather than the
toolchain. Two things follow from that and are deliberate:

* **The output asserts the original's origin.** Mirroring ``/Producer`` means a
  reportlab-rendered file reports the word processor that made the upload. That is the
  point of the feature — the candidate's own CV, carrying its own properties — but it is
  an assertion the bytes do not independently support, so it is confined to this module
  where it is easy to find and to change.
* **Only descriptive properties travel.** Never an id, a revision counter, or a template
  path: those describe a specific *file's* history, not the document, and copying them
  onto a different file makes them lies about lineage rather than about origin.

Pure and dependency-light on purpose: reading and stamping are separated from anything
that touches storage, so ``tailor`` stays a pure renderer and the runner does the I/O.
When the original has no readable properties — a scan, a stripped export, an unsupported
type — every function here degrades to neutral, honest values (the candidate's name and a
real timestamp) rather than inventing anything.
"""

from __future__ import annotations

import io
import logging
from datetime import datetime, timedelta, timezone

logger = logging.getLogger("jobpilot.doc_meta")

# The normalised property set. Deliberately descriptive-only: no identifier, no revision,
# no content_status, no template — see the module docstring.
FIELDS = (
    "title",
    "author",
    "subject",
    "keywords",
    "creator",
    "producer",
    "category",
    "comments",
    "last_modified_by",
    "created",
    "modified",
)

_PDF_INFO_KEYS = {
    "title": "/Title",
    "author": "/Author",
    "subject": "/Subject",
    "keywords": "/Keywords",
    "creator": "/Creator",
    "producer": "/Producer",
}

# reportlab and python-docx both write a placeholder when the caller sets nothing. Carrying
# one of those forward would defeat the whole point, so they are dropped on read: an absent
# property is more honest than "(unspecified)", and lets the neutral fallback take over.
_PLACEHOLDERS = {
    "",
    "(unspecified)",
    "(anonymous)",
    "unspecified",
    "generated by python-docx",
    "python-docx",
}
# python-docx's default template timestamp. Any document carrying it never had a real
# creation date, so it must not be mirrored onto anything.
_DOCX_TEMPLATE_EPOCH = datetime(2013, 12, 23, 23, 15, tzinfo=timezone.utc)


def _clean(value) -> str | None:
    """A property worth carrying, or None. Placeholders and blanks are not."""
    if value is None:
        return None
    text = str(value).strip()
    if not text or text.lower() in _PLACEHOLDERS:
        return None
    return text


def _clean_dt(value) -> datetime | None:
    """A timestamp worth carrying, or None."""
    if not isinstance(value, datetime):
        return None
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    if value == _DOCX_TEMPLATE_EPOCH:
        return None
    return value


# --------------------------------------------------------------------------- #
# Reading — best effort, never raises
# --------------------------------------------------------------------------- #
def read_doc_metadata(data: bytes) -> dict:
    """The descriptive properties of an uploaded CV, normalised to :data:`FIELDS`.

    Best effort by contract: an unreadable, encrypted, scanned or unsupported file yields
    ``{}`` and the caller falls back to neutral values. A CV export must never fail because
    its metadata could not be read — the document itself is the deliverable.
    """
    if not data:
        return {}
    try:
        if data[:4] == b"%PDF":
            return _read_pdf(data)
        if data[:4] == b"PK\x03\x04":  # zip container — try it as a docx
            return _read_docx(data)
    except Exception as exc:  # noqa: BLE001 - metadata is a nicety; the CV is the point
        logger.info("doc_meta.read failed (%s); falling back to neutral", type(exc).__name__)
    return {}


def _read_pdf(data: bytes) -> dict:
    from pypdf import PdfReader

    reader = PdfReader(io.BytesIO(data))
    info = reader.metadata
    if info is None:
        return {}
    out: dict = {}
    for field, key in _PDF_INFO_KEYS.items():
        cleaned = _clean(info.get(key))
        if cleaned is not None:
            out[field] = cleaned
    for field, attr in (("created", "creation_date"), ("modified", "modification_date")):
        try:
            cleaned_dt = _clean_dt(getattr(info, attr, None))
        except Exception:  # noqa: BLE001 - a malformed D: string must not sink the read
            cleaned_dt = None
        if cleaned_dt is not None:
            out[field] = cleaned_dt
    return out


def _read_docx(data: bytes) -> dict:
    import docx

    core = docx.Document(io.BytesIO(data)).core_properties
    out: dict = {}
    for field in ("title", "author", "subject", "keywords", "category", "comments",
                  "last_modified_by"):
        cleaned = _clean(getattr(core, field, None))
        if cleaned is not None:
            out[field] = cleaned
    # A DOCX has no /Producer or /Creator of its own; Word records the authoring app
    # nowhere in core properties, so a DOCX original simply carries no producer and the
    # PDF export falls back to neutral rather than guessing one.
    for field in ("created", "modified"):
        cleaned_dt = _clean_dt(getattr(core, field, None))
        if cleaned_dt is not None:
            out[field] = cleaned_dt
    return out


# --------------------------------------------------------------------------- #
# Resolving — what the export should actually claim
# --------------------------------------------------------------------------- #
def resolve(meta: dict | None, *, name: str = "", now: datetime | None = None) -> dict:
    """The properties to stamp: the original's where it had them, neutral values elsewhere.

    ``name`` is the candidate's name from the CV being rendered — the honest default for
    title/author when the upload carried none. Timestamps fall back to ``now`` rather than
    to any library default, which is what keeps 2013 out of the exports.
    """
    meta = {k: v for k, v in (meta or {}).items() if k in FIELDS and v is not None}
    stamp = datetime.now(timezone.utc) if now is None else now
    resolved = dict(meta)
    resolved.setdefault("author", _clean(name) or None)
    resolved.setdefault("title", _clean(name) or None)
    resolved.setdefault("created", stamp)
    # A tailored CV genuinely is modified now, even when it mirrors an older creation date:
    # that pairing is what an edited document looks like, and it is true of this one.
    resolved["modified"] = stamp
    return {k: v for k, v in resolved.items() if v is not None}


# --------------------------------------------------------------------------- #
# Stamping — PDF
# --------------------------------------------------------------------------- #
def _pdf_date(value: datetime) -> str:
    """A datetime as a PDF ``D:YYYYMMDDHHmmSS+HH'mm'`` string."""
    offset = value.utcoffset() or timedelta(0)
    minutes = int(offset.total_seconds()) // 60
    sign = "+" if minutes >= 0 else "-"
    hours, mins = divmod(abs(minutes), 60)
    return f"D:{value.strftime('%Y%m%d%H%M%S')}{sign}{hours:02d}'{mins:02d}'"


def stamp_pdf(pdf: bytes, meta: dict | None, *, name: str = "") -> bytes:
    """Rewrite a rendered PDF's info dictionary from ``meta``.

    Done as a post-pass rather than through reportlab's ``SimpleDocTemplate`` because
    reportlab owns ``/Producer`` and will not surrender it: it stamps its own name at save
    time whatever the caller passes. Rewriting the info dict afterwards is the only way to
    control the full set, and it leaves the rendered page content untouched.

    Falls back to returning the input unchanged if the rewrite fails — a CV with the wrong
    ``/Producer`` beats no CV at all.
    """
    resolved = resolve(meta, name=name)
    try:
        from pypdf import PdfReader, PdfWriter

        writer = PdfWriter(clone_from=io.BytesIO(pdf))
        info = {}
        for field, key in _PDF_INFO_KEYS.items():
            info[key] = resolved.get(field, "")
        for field, key in (("created", "/CreationDate"), ("modified", "/ModDate")):
            value = resolved.get(field)
            if isinstance(value, datetime):
                info[key] = _pdf_date(value)
        writer.add_metadata(info)
        buf = io.BytesIO()
        writer.write(buf)
        return buf.getvalue()
    except Exception as exc:  # noqa: BLE001 - never fail an export over its properties
        logger.warning("doc_meta.stamp_pdf failed (%s); leaving renderer defaults",
                       type(exc).__name__)
        return pdf


# --------------------------------------------------------------------------- #
# Stamping — DOCX
# --------------------------------------------------------------------------- #
def stamp_docx(document, meta: dict | None, *, name: str = "") -> None:
    """Set a python-docx ``Document``'s core properties from ``meta``, in place.

    ``created``/``modified`` are written as naive UTC: python-docx serialises core
    properties as W3CDTF in Zulu, and handing it an aware datetime it then re-offsets is
    how a document ends up an hour adrift from the original it was meant to match.
    """
    resolved = resolve(meta, name=name)
    core = document.core_properties
    for field in ("title", "author", "subject", "keywords", "category", "comments",
                  "last_modified_by"):
        # Assign even when absent: python-docx pre-fills some of these, and an empty
        # string is the only way to clear one it filled in for us.
        setattr(core, field, resolved.get(field, "") or "")
    for field in ("created", "modified"):
        value = resolved.get(field)
        if isinstance(value, datetime):
            setattr(core, field, value.astimezone(timezone.utc).replace(tzinfo=None))


# --------------------------------------------------------------------------- #
# Wire format — the properties cross an MCP boundary as JSON
# --------------------------------------------------------------------------- #
def to_jsonable(meta: dict | None) -> dict:
    """Properties as JSON: timestamps become ISO-8601 strings."""
    out: dict = {}
    for field, value in (meta or {}).items():
        if field not in FIELDS:
            continue
        out[field] = value.isoformat() if isinstance(value, datetime) else value
    return out


def from_jsonable(meta: dict | None) -> dict:
    """The inverse of :func:`to_jsonable`. An unparseable timestamp is dropped, not
    guessed at — the neutral fallback is better than a wrong date."""
    out: dict = {}
    for field, value in (meta or {}).items():
        if field not in FIELDS:
            continue
        if field in ("created", "modified"):
            if isinstance(value, datetime):
                out[field] = value
                continue
            try:
                out[field] = datetime.fromisoformat(str(value))
            except (TypeError, ValueError):
                continue
        else:
            out[field] = value
    return out
